-- Event tiers: a tier like Liquipedia's (S / A / B / C / D = liquipediatier
-- 1-5) and a kind (season / monthly / weekly / qualifier / misc); see
-- lib/event-tier.js. Admins can change both on the event page.
ALTER TABLE axsuck.tournaments
  ADD COLUMN IF NOT EXISTS tier TEXT CHECK (tier IN ('S', 'A', 'B', 'C', 'D')),
  ADD COLUMN IF NOT EXISTS event_kind TEXT CHECK (event_kind IN ('season', 'monthly', 'weekly', 'qualifier', 'misc'));

