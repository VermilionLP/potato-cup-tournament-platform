-- Events made on the site: by their points table, else a weekly by name.
UPDATE axsuck.tournaments
SET event_kind = CASE WHEN points_kind = 'monthly' THEN 'monthly' ELSE 'weekly' END,
    tier = CASE WHEN points_kind = 'monthly' THEN 'B' ELSE 'C' END
WHERE event_kind IS NULL AND tier IS NULL
  AND (points_kind IN ('weekly', 'monthly') OR name ~* 'weekly|周赛');
